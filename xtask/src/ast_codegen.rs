/// The two generated files, as text.
pub(crate) struct Generated {
    pub(crate) safe: String,
    pub(crate) raw: String,
}

pub(crate) fn safe_output() -> PathBuf {
    root().join("clingox/src/ast/generated.rs")
}

pub(crate) fn raw_output() -> PathBuf {
    root().join("clingox/src/raw/ast_generated.rs")
}

pub(crate) fn write() -> Result<()> {
    let generated = generate()?;
    if let Some(dir) = safe_output().parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(safe_output(), generated.safe)?;
    std::fs::write(raw_output(), generated.raw)?;
    eprintln!("wrote {}", safe_output().display());
    eprintln!("wrote {}", raw_output().display());
    Ok(())
}

/// Generates both files in memory, so `check` can compare without writing.
pub(crate) fn generate() -> Result<Generated> {
    let tables = read_tables()?;
    let constants = read_constants()?;
    assert_tables(&tables, &constants)?;
    let groups = resolve_groups(&constants)?;
    assert_groups(&tables, &groups)?;
    Ok(Generated {
        safe: finish(&safe_source(&tables, &groups))?,
        raw: finish_raw(&raw_source(&tables))?,
    })
}

