/// Parses and unparses `source`, so the bytes do not depend on `rustfmt`.
fn unparse(source: &str) -> Result<String> {
    let file =
        syn::parse_file(source).map_err(|e| format!("the generated source does not parse: {e}"))?;
    Ok(prettyplease::unparse(&file))
}

fn finish(source: &str) -> Result<String> {
    Ok(format!("{HEADER}{}", unparse(source)?))
}

/// As [`finish`], and restores the `SAFETY` comment that `prettyplease` would
/// drop with every other plain comment.
fn finish_raw(source: &str) -> Result<String> {
    let text = unparse(source)?;
    let marker = "    unsafe {\n";
    let Some(at) = text.find(marker) else {
        return Err("the generated raw source lost its unsafe block".into());
    };
    let mut with_comment = String::with_capacity(text.len() + 1024);
    with_comment.push_str(&text[..at]);
    for line in RAW_SAFETY {
        with_comment.push_str("    // ");
        with_comment.push_str(line);
        with_comment.push('\n');
    }
    with_comment.push_str(&text[at..]);
    Ok(format!("{HEADER}{with_comment}"))
}
