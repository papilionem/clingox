//! `cargo xtask ast-codegen`: the typed layer over `clingo_ast_build`, written
//! from clingo's own constructor table.
//!
//! The tables `g_clingo_ast_constructors` and `g_clingo_ast_attribute_names`
//! are read at run time through `clingox-sys`, because clingo exports them for
//! exactly this purpose ("enough information to auto-generate code for
//! language bindings", `clingo.h`). The committed `bindings.rs` is read only as
//! text, to enumerate the `clingo_ast_*` constants the tables must agree with.
//!
//! Two files come out: `clingox/src/ast/generated.rs`, the safe layer (the
//! nine enum types, the constructors, the visitor and two crate-private
//! tables), and `clingox/src/raw/ast_generated.rs`, the one place the variadic
//! `clingo_ast_build` is called. Both go through `syn` and `prettyplease`, so
//! the bytes do not depend on the installed `rustfmt`, and `cargo xtask check`
//! compares them with the committed files.

