fn read_tables() -> Result<Tables> {
    // SAFETY: both are plain C structs that clingo's translation unit
    // initializes before `main` (`control.cc`, `g_clingo_ast_*`), and nothing
    // writes to them; copying the two-word struct reads it once.
    let (constructors, names) = unsafe {
        (
            (&raw const ffi::g_clingo_ast_constructors).read(),
            (&raw const ffi::g_clingo_ast_attribute_names).read(),
        )
    };
    // SAFETY: `names` points to `size` NUL-terminated strings with static
    // storage duration (clingo.h, `clingo_ast_attribute_names_t`).
    let name_list = unsafe { std::slice::from_raw_parts(names.names, names.size) };
    let attributes = name_list
        .iter()
        .map(|&name| {
            // SAFETY: each entry is a NUL-terminated string with static storage.
            unsafe { CStr::from_ptr(name) }.to_str().map(str::to_owned)
        })
        .collect::<std::result::Result<Vec<_>, _>>()?;
    // SAFETY: `constructors` points to `size` entries with static storage.
    let entries =
        unsafe { std::slice::from_raw_parts(constructors.constructors, constructors.size) };
    let mut list = Vec::new();
    for entry in entries {
        // SAFETY: `name` is NUL-terminated with static storage, and
        // `arguments` points to `size` entries with static storage.
        let (name, arguments) = unsafe {
            (
                CStr::from_ptr(entry.name).to_str()?.to_owned(),
                std::slice::from_raw_parts(entry.arguments, entry.size),
            )
        };
        list.push(Constructor {
            name,
            arguments: arguments
                .iter()
                .map(|a| {
                    Ok(Argument {
                        attribute: usize::try_from(a.attribute)?,
                        kind: usize::try_from(a.type_)?,
                    })
                })
                .collect::<Result<_>>()?,
        });
    }
    Ok(Tables {
        constructors: list,
        attributes,
    })
}

/// Every integer constant of the committed bindings that has a `_e` C type.
fn read_constants() -> Result<Vec<Constant>> {
    let text = std::fs::read_to_string(bindings::output())?;
    let file = syn::parse_file(&text)?;
    let mut constants = Vec::new();
    for item in file.items {
        let syn::Item::Const(item) = item else {
            continue;
        };
        let syn::Type::Path(ty) = &*item.ty else {
            continue;
        };
        let Some(c_type) = ty.path.get_ident().map(ToString::to_string) else {
            continue;
        };
        if !c_type.ends_with("_e") {
            continue;
        }
        let syn::Expr::Lit(syn::ExprLit {
            lit: syn::Lit::Int(value),
            ..
        }) = &*item.expr
        else {
            continue;
        };
        constants.push(Constant {
            name: item.ident.to_string(),
            c_type,
            value: value.base10_parse()?,
        });
    }
    Ok(constants)
}

