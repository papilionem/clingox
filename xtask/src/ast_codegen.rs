fn assert_tables(tables: &Tables, constants: &[Constant]) -> Result<()> {
    let types: Vec<&Constant> = constants
        .iter()
        .filter(|c| c.c_type == "clingo_ast_type_e")
        .collect();
    if types.len() != tables.constructors.len() {
        return Err(format!(
            "the constructor table has {} entries, but the header defines {} clingo_ast_type_* constants",
            tables.constructors.len(),
            types.len()
        )
        .into());
    }
    for (index, constructor) in tables.constructors.iter().enumerate() {
        let constant = format!("clingo_ast_type_{}", constructor.name);
        let found = types.iter().find(|c| c.name == constant);
        match found {
            Some(c) if usize::try_from(c.value) == Ok(index) => {}
            Some(c) => {
                return Err(format!(
                    "constructor {index} is `{}`, but {constant} has value {}",
                    constructor.name, c.value
                )
                .into());
            }
            None => {
                return Err(format!(
                    "constructor {index} is `{}`, but the header has no {constant}",
                    constructor.name
                )
                .into());
            }
        }
        for name in [&constructor.name] {
            if name.is_empty() || name.starts_with('_') {
                return Err(format!("constructor {index} has the unusable name {name:?}").into());
            }
        }
    }

    let attributes: Vec<&Constant> = constants
        .iter()
        .filter(|c| c.c_type == "clingo_ast_attribute_e")
        .collect();
    if attributes.len() != tables.attributes.len() {
        return Err(format!(
            "the attribute name table has {} entries, but the header defines {} clingo_ast_attribute_* constants",
            tables.attributes.len(),
            attributes.len()
        )
        .into());
    }
    for (index, name) in tables.attributes.iter().enumerate() {
        let constant = format!("clingo_ast_attribute_{name}");
        let ok = attributes
            .iter()
            .any(|c| c.name == constant && usize::try_from(c.value) == Ok(index));
        if !ok {
            return Err(format!(
                "attribute name {index} is `{name}`, but the header has no {constant} = {index}"
            )
            .into());
        }
        if KEYWORDS.contains(&name.as_str()) {
            return Err(format!(
                "attribute `{name}` is a Rust keyword; the generator needs a rename"
            )
            .into());
        }
    }

    for constructor in &tables.constructors {
        for argument in &constructor.arguments {
            if argument.attribute >= tables.attributes.len() {
                return Err(format!(
                    "constructor `{}` names attribute {}, beyond the {} names",
                    constructor.name,
                    argument.attribute,
                    tables.attributes.len()
                )
                .into());
            }
            if argument.kind >= ATTRIBUTE_TYPES {
                return Err(format!(
                    "constructor `{}` has an argument of type {}, beyond the {ATTRIBUTE_TYPES} kinds",
                    constructor.name, argument.kind
                )
                .into());
            }
        }
    }
    Ok(())
}

/// The constants of one enum type, in value order, with their Rust names.
struct Group {
    spec: &'static EnumGroup,
    /// `(rust variant, constant name, value)`.
    variants: Vec<(String, String, i64)>,
}

fn resolve_groups(constants: &[Constant]) -> Result<Vec<Group>> {
    // Assertion 4: every enum group of the header is mapped.
    let mut known: BTreeMap<&str, usize> = BTreeMap::new();
    for constant in constants {
        *known.entry(constant.c_type.as_str()).or_default() += 1;
    }
    let structural = [
        "clingo_ast_type_e",
        "clingo_ast_attribute_e",
        "clingo_ast_attribute_type_e",
    ];
    for c_type in known.keys() {
        let is_ast = c_type.starts_with("clingo_ast_") || *c_type == "clingo_comment_type_e";
        if is_ast
            && !structural.contains(c_type)
            && !UNMAPPED_GROUPS.contains(c_type)
            && !GROUPS.iter().any(|group| group.c_type == *c_type)
        {
            return Err(format!(
                "the header defines the enum {c_type}, which the generator does not map; add it to GROUPS in xtask/src/ast_codegen.rs"
            )
            .into());
        }
    }
    let mut groups = Vec::new();
    for spec in &GROUPS {
        let prefix = spec.c_type.trim_end_matches("_e");
        let mut variants: Vec<(String, String, i64)> = constants
            .iter()
            .filter(|c| c.c_type == spec.c_type)
            .map(|c| {
                let suffix = c
                    .name
                    .strip_prefix(prefix)
                    .and_then(|rest| rest.strip_prefix('_'))
                    .unwrap_or(&c.name);
                let name = spec
                    .renames
                    .iter()
                    .find(|(from, _)| *from == suffix)
                    .map_or_else(|| camel(suffix), |(_, to)| (*to).to_owned());
                (name, c.name.clone(), c.value)
            })
            .collect();
        if variants.is_empty() {
            return Err(format!("the header has no constants of type {}", spec.c_type).into());
        }
        variants.sort_by_key(|v| v.2);
        for (index, variant) in variants.iter().enumerate() {
            if usize::try_from(variant.2) != Ok(index) {
                return Err(format!(
                    "{}: the constants are not 0, 1, 2, ...; {} has value {}",
                    spec.c_type, variant.1, variant.2
                )
                .into());
            }
        }
        groups.push(Group { spec, variants });
    }
    Ok(groups)
}

/// Assertion 3: every mapped (constructor, attribute) pair is a number
/// argument, and every other number argument is accounted for.
fn assert_groups(tables: &Tables, groups: &[Group]) -> Result<()> {
    let pairs = groups
        .iter()
        .flat_map(|g| g.spec.used_by.iter())
        .chain(BOOLEANS.iter())
        .chain(PLAIN_NUMBERS.iter())
        .chain(ARITIES.iter());
    for &(constructor, attribute) in pairs {
        let found = tables
            .constructors
            .iter()
            .find(|c| c.name == constructor)
            .is_some_and(|c| {
                c.arguments
                    .iter()
                    .any(|a| a.kind == NUMBER && tables.attributes[a.attribute] == attribute)
            });
        if !found {
            return Err(format!(
                "the generator maps `{constructor}.{attribute}` as a number, but the constructor table has no such argument"
            )
            .into());
        }
    }
    for constructor in &tables.constructors {
        for argument in constructor.arguments.iter().filter(|a| a.kind == NUMBER) {
            let attribute = &tables.attributes[argument.attribute];
            if number_kind(groups, &constructor.name, attribute).is_none() {
                return Err(format!(
                    "the number argument `{}.{attribute}` is not mapped to an enum, a boolean or a plain number in xtask/src/ast_codegen.rs",
                    constructor.name
                )
                .into());
            }
        }
    }
    Ok(())
}

enum NumberKind<'a> {
    Enum(&'a Group),
    Bool,
    Plain,
    NonNegative,
}

fn number_kind<'a>(
    groups: &'a [Group],
    constructor: &str,
    attribute: &str,
) -> Option<NumberKind<'a>> {
    if let Some(group) = groups
        .iter()
        .find(|g| g.spec.used_by.contains(&(constructor, attribute)))
    {
        return Some(NumberKind::Enum(group));
    }
    if BOOLEANS.contains(&(constructor, attribute)) {
        return Some(NumberKind::Bool);
    }
    if ARITIES.contains(&(constructor, attribute)) {
        return Some(NumberKind::NonNegative);
    }
    PLAIN_NUMBERS
        .contains(&(constructor, attribute))
        .then_some(NumberKind::Plain)
}

