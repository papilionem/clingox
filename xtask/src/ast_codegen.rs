fn safe_source(tables: &Tables, groups: &[Group]) -> String {
    let mut out = String::new();
    out.push_str(
        "//! The typed layer over `clingo_ast_build`: the enum types of the number\n\
         //! attributes, one constructor per node type, the visitor, and two\n\
         //! crate-private tables the setters and the visitor read.\n\
         //!\n\
         //! Generated from clingo's own constructor table by `cargo xtask ast-codegen`.\n\n\
         #![allow(\n\
         \x20   clippy::match_same_arms,\n\
         \x20   clippy::too_many_lines,\n\
         \x20   reason = \"generated from a table: arms repeat, and the functions are as long as the table\"\n\
         )]\n\n\
         use super::{Ast, AstType, Attribute, AttributeType, Span};\n\
         use crate::Symbol;\n\
         use crate::error::{Error, ErrorKind, Result};\n\
         use crate::raw::{self, BuildArg};\n\n",
    );

    for group in groups {
        enum_source(&mut out, group);
    }

    for constructor in &tables.constructors {
        constructor_source(&mut out, tables, groups, constructor);
    }

    tables_source(&mut out, tables, groups);
    visitor_source(&mut out, tables);
    out
}

fn enum_source(out: &mut String, group: &Group) {
    let name = group.spec.rust_name;
    let last = group.variants.last().map_or(0, |v| v.2);
    let _ = writeln!(out, "/// {}", group.spec.doc);
    let _ = writeln!(out, "///");
    let _ = writeln!(
        out,
        "/// Converts to and from the `i32` clingo stores: `i32::from(value)`, and"
    );
    let _ = writeln!(
        out,
        "/// `{name}::try_from(number)`, which is [`ErrorKind::InvalidInput`] outside `0..={last}`."
    );
    out.push_str(
        "#[non_exhaustive]\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n#[repr(i32)]\n",
    );
    let _ = writeln!(out, "pub enum {name} {{");
    for (variant, constant, value) in &group.variants {
        let _ = writeln!(out, "    /// `{constant}`, {value}.");
        let _ = writeln!(out, "    {variant} = {value},");
    }
    out.push_str("}\n\n");
    let _ = writeln!(
        out,
        "impl From<{name}> for i32 {{\n    fn from(value: {name}) -> i32 {{\n        value as i32\n    }}\n}}\n"
    );
    let _ = writeln!(out, "impl TryFrom<i32> for {name} {{");
    out.push_str("    type Error = Error;\n\n");
    out.push_str("    fn try_from(value: i32) -> Result<Self> {\n        match value {\n");
    for (variant, _, value) in &group.variants {
        let _ = writeln!(out, "            {value} => Ok({name}::{variant}),");
    }
    let _ = writeln!(
        out,
        "            _ => Err(Error::new(\n                ErrorKind::InvalidInput,\n                format!(\"{{value}} is not a `{name}` (0..={last})\"),\n            )),"
    );
    out.push_str("        }\n    }\n}\n\n");
}

/// The Rust parameter type, and the expression that turns it into a
/// `BuildArg`, of one constructor argument.
fn parameter(
    groups: &[Group],
    tables: &Tables,
    constructor: &Constructor,
    argument: &Argument,
) -> (String, String, String) {
    let attribute = tables.attributes[argument.attribute].as_str();
    let (ty, arg) = match argument.kind {
        NUMBER => match number_kind(groups, &constructor.name, attribute) {
            Some(NumberKind::Enum(group)) => (
                group.spec.rust_name.to_owned(),
                format!("BuildArg::Number(i32::from({attribute}))"),
            ),
            Some(NumberKind::Bool) => (
                "bool".to_owned(),
                format!("BuildArg::Number(i32::from({attribute}))"),
            ),
            _ => ("i32".to_owned(), format!("BuildArg::Number({attribute})")),
        },
        SYMBOL => (
            "Symbol".to_owned(),
            format!("BuildArg::Symbol({attribute})"),
        ),
        LOCATION => ("&Span".to_owned(), format!("BuildArg::Span({attribute})")),
        STRING => ("&str".to_owned(), format!("BuildArg::Str({attribute})")),
        AST => ("&Ast".to_owned(), format!("BuildArg::Ast({attribute})")),
        OPTIONAL_AST => (
            "Option<&Ast>".to_owned(),
            format!("BuildArg::OptionalAst({attribute})"),
        ),
        STRING_ARRAY => (
            "&[impl AsRef<str>]".to_owned(),
            format!("BuildArg::StrArray(&{attribute})"),
        ),
        AST_ARRAY => (
            "&[Ast]".to_owned(),
            format!("BuildArg::AstArray({attribute})"),
        ),
        other => unreachable!("assert_tables rejected the attribute type {other}"),
    };
    // A string array needs its `&str` view before the call.
    let prelude = if argument.kind == STRING_ARRAY {
        format!(
            "    let {attribute}: Vec<&str> = {attribute}.iter().map(AsRef::as_ref).collect();\n"
        )
    } else if argument.kind == NUMBER
        && matches!(
            number_kind(groups, &constructor.name, attribute),
            Some(NumberKind::NonNegative)
        )
    {
        format!(
            "    if {attribute} < 0 {{\n        return Err(Error::new(\n            ErrorKind::InvalidInput,\n            format!(\"{{{attribute}}} is not an arity, which is at least 0\"),\n        ));\n    }}\n"
        )
    } else {
        String::new()
    };
    (ty, arg, prelude)
}

fn constructor_source(
    out: &mut String,
    tables: &Tables,
    groups: &[Group],
    constructor: &Constructor,
) {
    let name = &constructor.name;
    let variant = camel(name);
    let mut params = Vec::new();
    let mut args = Vec::new();
    let mut prelude = String::new();
    let mut doc_params = String::new();
    let mut nul = false;
    let mut arity = false;
    for argument in &constructor.arguments {
        let attribute = tables.attributes[argument.attribute].as_str();
        let (ty, arg, pre) = parameter(groups, tables, constructor, argument);
        params.push(format!("{attribute}: {ty}"));
        args.push(arg);
        prelude.push_str(&pre);
        nul |= argument.kind == STRING || argument.kind == STRING_ARRAY;
        arity |= argument.kind == NUMBER
            && matches!(
                number_kind(groups, name, attribute),
                Some(NumberKind::NonNegative)
            );
        let _ = writeln!(
            doc_params,
            "/// - `{attribute}`: [`Attribute::{}`], a `{ty}`.",
            camel(attribute)
        );
    }
    let _ = writeln!(out, "/// Builds a [`AstType::{variant}`] node.");
    let _ = writeln!(out, "///");
    let _ = writeln!(
        out,
        "/// The arguments follow clingo's constructor table for the type, in order:"
    );
    let _ = writeln!(out, "///");
    out.push_str(&doc_params);
    let _ = writeln!(out, "///");
    let _ = writeln!(
        out,
        "/// Every node argument is borrowed: the new node holds its own reference, and\n\
         /// the caller's handles stay valid. The result is a new top node, and shares\n\
         /// its children with the arguments. What kind of node an argument is is not\n\
         /// checked."
    );
    let _ = writeln!(out, "///");
    let _ = writeln!(out, "/// # Errors");
    let _ = writeln!(out, "///");
    if arity {
        let _ = writeln!(
            out,
            "/// - [`ErrorKind::InvalidInput`] if `arity` is negative;"
        );
    }
    if nul {
        let _ = writeln!(
            out,
            "/// - [`ErrorKind::Nul`] if a string contains a NUL byte;"
        );
    }
    let _ = writeln!(
        out,
        "/// - [`ErrorKind::BadAlloc`] if clingo runs out of memory."
    );
    if arity {
        let _ = writeln!(out, "///");
        let _ = writeln!(
            out,
            "/// A huge arity is accepted, because it is clingo's own limit: adding a\n\
             /// `project_signature` with an arity in the hundreds of millions to a program\n\
             /// makes clingo allocate one variable per argument until memory runs out\n\
             /// (UPSTREAM-ISSUES U48), as the text `#project p/4294967295.` does."
        );
    }
    out.push_str(extra_docs(name));
    let _ = writeln!(
        out,
        "pub fn {name}({}) -> Result<Ast> {{",
        params.join(", ")
    );
    out.push_str(&prelude);
    let _ = writeln!(
        out,
        "    raw::ast_build(AstType::{variant}, &[{}])\n        .map(Ast::from_raw)\n        .map_err(|e| e.context(\"building a `{name}` node\"))\n}}\n",
        args.join(", ")
    );
}

fn tables_source(out: &mut String, tables: &Tables, groups: &[Group]) {
    out.push_str(
        "/// The values a `number` attribute may take on a node of a given type.\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]\n\
         pub(crate) enum NumberDomain {\n\
         \x20   /// Any `i32`.\n\
         \x20   Any,\n\
         \x20   /// A boolean, stored as 0 or 1.\n\
         \x20   Bool,\n\
         \x20   /// `0..=max`: an enum's constants, or `0..=i32::MAX` for an arity.\n\
         \x20   Range(i32),\n\
         }\n\n",
    );

    out.push_str(
        "/// The domain of `attribute` on a node of type `kind` (`set_number`).\n\
         pub(crate) fn number_domain(kind: AstType, attribute: Attribute) -> NumberDomain {\n\
         \x20   match (kind, attribute) {\n",
    );
    for constructor in &tables.constructors {
        for argument in constructor.arguments.iter().filter(|a| a.kind == NUMBER) {
            let attribute = tables.attributes[argument.attribute].as_str();
            let domain = match number_kind(groups, &constructor.name, attribute) {
                Some(NumberKind::Enum(group)) => {
                    let max = group.variants.last().map_or(0, |v| v.2);
                    format!("NumberDomain::Range({max})")
                }
                Some(NumberKind::Bool) => "NumberDomain::Bool".to_owned(),
                Some(NumberKind::NonNegative) => "NumberDomain::Range(i32::MAX)".to_owned(),
                _ => continue,
            };
            let _ = writeln!(
                out,
                "        (AstType::{}, Attribute::{}) => {domain},",
                camel(&constructor.name),
                camel(attribute)
            );
        }
    }
    out.push_str("        _ => NumberDomain::Any,\n    }\n}\n\n");

    out.push_str(
        "/// The attributes of `kind` that hold nodes, in constructor order.\n\
         pub(crate) fn child_attributes(kind: AstType) -> &'static [(Attribute, AttributeType)] {\n\
         \x20   match kind {\n",
    );
    for constructor in &tables.constructors {
        let children: Vec<String> = constructor
            .arguments
            .iter()
            .filter(|a| matches!(a.kind, AST | OPTIONAL_AST | AST_ARRAY))
            .map(|a| {
                let kind = match a.kind {
                    AST => "Ast",
                    OPTIONAL_AST => "OptionalAst",
                    _ => "AstArray",
                };
                format!(
                    "(Attribute::{}, AttributeType::{kind})",
                    camel(&tables.attributes[a.attribute])
                )
            })
            .collect();
        if children.is_empty() {
            continue;
        }
        let _ = writeln!(
            out,
            "        AstType::{} => &[{}],",
            camel(&constructor.name),
            children.join(", ")
        );
    }
    out.push_str("        _ => &[],\n    }\n}\n\n");
}

fn visitor_source(out: &mut String, tables: &Tables) {
    out.push_str(
        "/// Rewrites a syntax tree: one method per node type, each defaulting to\n\
         /// [`walk`], which visits the node's children.\n\
         ///\n\
         /// Every method takes a borrowed node and returns an owned one. Returning\n\
         /// a clone of the argument means \"unchanged\"; returning any other node\n\
         /// replaces it, and the replacement may be of a different type. A child\n\
         /// counts as changed exactly when the node returned for it is not\n\
         /// [`Ast::ptr_eq`] to the original (identity, as pyclingo's `is not`), so\n\
         /// an unchanged subtree is shared, not copied, and [`walk`] returns the\n\
         /// very node it was given when nothing below it changed.\n\
         ///\n\
         /// The first error any method returns stops the whole walk and is returned\n\
         /// unchanged. The original tree is never modified by `walk`, also on an\n\
         /// error.\n\
         ///\n\
         /// A visitor must not edit the tree it walks, whether through a setter on\n\
         /// the node it was given or on one of its children: [`walk`] reads the\n\
         /// children as it goes, so the result of such an edit is a silently\n\
         /// partial rewrite. Nothing is unsafe about it (every index is checked),\n\
         /// but it is not the tree you meant. Edit a `copy()` instead.\n\
         ///\n\
         /// `visit` dispatches on the node's type and should not be overridden.\n\
         /// The trait is object safe: `&mut dyn Visitor` works.\n\
         ///\n\
         /// # Deleting and inserting array elements\n\
         ///\n\
         /// [`walk`] replaces array elements one for one, as pyclingo's\n\
         /// `Transformer` does by default. To delete or insert elements, call\n\
         /// [`walk`] and edit the result, but `copy()` it first when it is\n\
         /// [`Ast::ptr_eq`] to the input: nothing below it changed, so it *is* the\n\
         /// original node, and editing it would edit the original tree.\n\
         ///\n\
         /// ```\n\
         /// use clingox::ast::{self, Ast, AstType, Attribute, Visitor, walk};\n\
         /// use clingox::Result;\n\
         ///\n\
         /// /// Drops the first body literal of every rule.\n\
         /// struct DropFirst;\n\
         ///\n\
         /// impl Visitor for DropFirst {\n\
         ///     fn visit_rule(&mut self, node: &Ast) -> Result<Ast> {\n\
         ///         let walked = walk(self, node)?;\n\
         ///         let edited = if walked.ptr_eq(node) { walked.copy()? } else { walked };\n\
         ///         if edited.ast_array_len(Attribute::Body)? > 0 {\n\
         ///             edited.delete_ast_at(Attribute::Body, 0)?;\n\
         ///         }\n\
         ///         Ok(edited)\n\
         ///     }\n\
         /// }\n\
         ///\n\
         /// let mut rules = Vec::new();\n\
         /// ast::parse_string(\"h :- a, b.\", |node| {\n\
         ///     if node.ast_type() == AstType::Rule {\n\
         ///         rules.push(node);\n\
         ///     }\n\
         ///     Ok(())\n\
         /// })?;\n\
         /// let rewritten = DropFirst.visit(&rules[0])?;\n\
         /// assert_eq!(rewritten.to_string(), \"h :- b.\");\n\
         /// assert_eq!(rules[0].to_string(), \"h :- a; b.\");\n\
         /// # Ok::<(), clingox::Error>(())\n\
         /// ```\n\
         pub trait Visitor {\n\
         \x20   /// Dispatches on `node.ast_type()` to the matching `visit_*` method.\n\
         \x20   ///\n\
         \x20   /// # Errors\n\
         \x20   ///\n\
         \x20   /// Whatever the method it calls returns.\n\
         \x20   fn visit(&mut self, node: &Ast) -> Result<Ast> {\n\
         \x20       match node.ast_type() {\n",
    );
    for constructor in &tables.constructors {
        let _ = writeln!(
            out,
            "            AstType::{} => self.visit_{}(node),",
            camel(&constructor.name),
            constructor.name
        );
    }
    out.push_str(
        "            AstType::Other(_) => self.visit_other(node),\n\
         \x20       }\n\
         \x20   }\n\n",
    );
    for constructor in &tables.constructors {
        let _ = writeln!(
            out,
            "    /// Visits a [`AstType::{}`] node. Defaults to [`walk`].\n\
             \x20   ///\n\
             \x20   /// # Errors\n\
             \x20   ///\n\
             \x20   /// As [`Visitor::visit`].\n\
             \x20   fn visit_{}(&mut self, node: &Ast) -> Result<Ast> {{\n\
             \x20       walk(self, node)\n\
             \x20   }}\n",
            camel(&constructor.name),
            constructor.name
        );
    }
    out.push_str(
        "    /// Visits a node of a type this build does not know ([`AstType::Other`]).\n\
         \x20   /// Defaults to returning the node unchanged.\n\
         \x20   ///\n\
         \x20   /// # Errors\n\
         \x20   ///\n\
         \x20   /// As [`Visitor::visit`].\n\
         \x20   fn visit_other(&mut self, node: &Ast) -> Result<Ast> {\n\
         \x20       Ok(node.clone())\n\
         \x20   }\n\
         }\n\n",
    );

    out.push_str(
        "/// Visits the children of `node` through `visitor` and rebuilds `node` when\n\
         /// any of them changed.\n\
         ///\n\
         /// For each child attribute of the node's type, in constructor order:\n\
         /// an `ast` attribute is visited, an `optional_ast` is skipped when it is\n\
         /// `None` and visited otherwise, and every element of an `ast_array` is\n\
         /// visited in index order, one replacement per element (the length cannot\n\
         /// change here). Other attributes (`location`, names, symbols, numbers,\n\
         /// strings) are never visited.\n\
         ///\n\
         /// If no child changed, the result is a clone of `node`, so it is\n\
         /// [`Ast::ptr_eq`] to it and nothing is allocated. Otherwise the result is\n\
         /// `node.copy()` with only the changed children replaced: unchanged\n\
         /// children and siblings stay shared with the original, and every other\n\
         /// attribute, the location included, is kept. The original is never\n\
         /// modified.\n\
         ///\n\
         /// An override can call `walk` before or after its own edits. See\n\
         /// [`Visitor`] for how to delete or insert array elements.\n\
         ///\n\
         /// # Stack use\n\
         ///\n\
         /// `walk` recurses once per level of the tree, through\n\
         /// [`Visitor::visit`], like pyclingo's `Transformer`, and has no depth\n\
         /// limit of its own. A tree deep enough to exhaust the thread's stack\n\
         /// overflows it. Printing, comparing and dropping such a tree recurse in\n\
         /// clingo the same way, so a tree that clingo itself can print on a\n\
         /// thread can also be walked on it; run a visitor over very deep trees on\n\
         /// a thread with a large stack.\n\
         ///\n\
         /// # Errors\n\
         ///\n\
         /// The first error any `visit_*` method, setter or `copy` reports, which\n\
         /// is returned unchanged.\n\
         pub fn walk<V: Visitor + ?Sized>(visitor: &mut V, node: &Ast) -> Result<Ast> {\n\
         \x20   let mut rebuilt: Option<Ast> = None;\n\
         \x20   for &(attribute, kind) in child_attributes(node.ast_type()) {\n\
         \x20       match kind {\n\
         \x20           AttributeType::Ast => {\n\
         \x20               let child = node.ast(attribute)?;\n\
         \x20               let visited = visitor.visit(&child)?;\n\
         \x20               if !visited.ptr_eq(&child) {\n\
         \x20                   copy_of(&mut rebuilt, node)?.set_ast_fresh(attribute, &visited)?;\n\
         \x20               }\n\
         \x20           }\n\
         \x20           AttributeType::OptionalAst => {\n\
         \x20               if let Some(child) = node.optional_ast(attribute)? {\n\
         \x20                   let visited = visitor.visit(&child)?;\n\
         \x20                   if !visited.ptr_eq(&child) {\n\
         \x20                       copy_of(&mut rebuilt, node)?\n\
         \x20                           .set_optional_ast_fresh(attribute, &visited)?;\n\
         \x20                   }\n\
         \x20               }\n\
         \x20           }\n\
         \x20           AttributeType::AstArray => {\n\
         \x20               for index in 0..node.ast_array_len(attribute)? {\n\
         \x20                   let child = node.ast_at(attribute, index)?;\n\
         \x20                   let visited = visitor.visit(&child)?;\n\
         \x20                   if !visited.ptr_eq(&child) {\n\
         \x20                       copy_of(&mut rebuilt, node)?\n\
         \x20                           .set_ast_at_fresh(attribute, index, &visited)?;\n\
         \x20                   }\n\
         \x20               }\n\
         \x20           }\n\
         \x20           _ => {}\n\
         \x20       }\n\
         \x20   }\n\
         \x20   Ok(rebuilt.unwrap_or_else(|| node.clone()))\n\
         }\n\n\
         /// The private copy `walk` edits: made on the first change, and a handle to\n\
         /// the same node afterwards.\n\
         ///\n\
         /// This is why `walk` may use the setters that skip the cycle check: the copy\n\
         /// is new, and only `walk` holds a handle to it until `walk` returns. A\n\
         /// replacement a visitor returns was made before the copy could be reached,\n\
         /// so it cannot reach the copy, and adding it below the copy cannot close a\n\
         /// cycle. The original tree is only read.\n\
         fn copy_of(rebuilt: &mut Option<Ast>, node: &Ast) -> Result<Ast> {\n\
         \x20   if let Some(copy) = rebuilt {\n\
         \x20       return Ok(copy.clone());\n\
         \x20   }\n\
         \x20   let copy = node.copy()?;\n\
         \x20   *rebuilt = Some(copy.clone());\n\
         \x20   Ok(copy)\n\
         }\n",
    );
}

